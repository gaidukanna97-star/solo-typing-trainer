/** Таблиця «палець → клавіші» для обох розкладок, побудована з тієї самої схеми, що й тренажер. */
function fingerTable() {
  const keysOf = (layout, finger) => KEYS
    .filter((k) => k.finger === finger && k.row >= 1 && k.row <= 3)
    .map((k) => layout.byCode[k.code].base)
    .filter((ch) => ch !== '\\')
    .map((ch) => (layout.letters.test(ch) ? ch.toUpperCase() : ch));
  const home = (layout, finger) => layout.byCode[HOME_CODE[finger]].base.toUpperCase();
  const rows = FINGER_ORDER.map((f) => `
    <tr>
      <th scope="row"><span class="kb-swatch f-${f}"></span>${esc(FINGERS[f].name)}</th>
      <td><strong>${esc(home(LAYOUTS.uk, f))}</strong></td>
      <td>${keysOf(LAYOUTS.uk, f).map(esc).join(' ')}</td>
      <td><strong>${esc(home(LAYOUTS.en, f))}</strong></td>
      <td>${keysOf(LAYOUTS.en, f).map(esc).join(' ')}</td>
    </tr>`).join('');
  return `<div class="scroll"><table class="finger-table">
    <thead><tr><th>Палець</th><th>Домашня клавіша (укр.)</th><th>Усі клавіші (укр.)</th><th>Домашня клавіша (англ.)</th><th>Усі клавіші (англ.)</th></tr></thead>
    <tbody>${rows}
      <tr><th scope="row"><span class="kb-swatch f-th"></span>великі пальці</th><td colspan="4">пробіл — тим великим пальцем, яким зручніше</td></tr>
    </tbody></table></div>`;
}

